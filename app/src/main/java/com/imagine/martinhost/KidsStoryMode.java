package com.imagine.martinhost;

import android.content.Context;

public final class KidsStoryMode {
    private final Context context;
    public KidsStoryMode(Context context){ this.context=context.getApplicationContext(); }

    public String interviewPrompt(String childName, int age){
        String name=(childName==null||childName.isBlank())?"малыш":childName.trim();
        int safeAge=Math.max(3,Math.min(age,7));
        return "Ты Мартинёнок — добрый голосовой собеседник для ребёнка "+safeAge+" лет по имени "+name+". " +
                "Проведи очень короткий разговор о сегодняшнем дне. Задавай только ОДИН простой вопрос за раз и жди ответа. " +
                "Начни с «Как прошёл твой день?» Затем мягко уточни: что было самым весёлым, что получилось хорошо, было ли что-то трудное или неприятное, что ребёнок сделал в такой ситуации, и чего бы он хотел завтра. " +
                "Не допрашивай, не оценивай и не спорь. Если ребёнок не хочет отвечать — спокойно смени тему. После 4–6 коротких ответов предложи: «Хочешь, я превращу твой день в сказку?»";
    }

    public String fairyTalePrompt(String childName, int age, String dayStory){
        String name=(childName==null||childName.isBlank())?"главный герой":childName.trim();
        int safeAge=Math.max(3,Math.min(age,7));
        String story=dayStory==null?"":dayStory.trim();
        return "Создай добрую персональную сказку для ребёнка "+safeAge+" лет. Главный герой — "+name+". " +
                "Основа сказки — рассказ ребёнка о дне: «"+story+"». " +
                "Сделай историю на 4–7 минут озвучки, простыми словами, с приключением, юмором, повторяющимся забавным элементом и тёплым финалом. " +
                "Если в рассказе была трудность (ссора, не захотел ждать, расстроился, испугался, не послушал, что-то не получилось и т.п.), НЕ ругай ребёнка и не читай мораль напрямую. " +
                "Покажи похожую ситуацию внутри сказки через вымышленного героя и понятное последствие, а затем покажи 1–2 безопасных и добрых способа поступить лучше: попросить помощь, сказать словами, подождать очередь, попробовать ещё раз, извиниться, отойти и успокоиться, обратиться к взрослому. " +
                "Не ставь диагнозов и не делай выводов о характере ребёнка. Не говори, что ребёнок плохой или виноват. В конце задай один мягкий вопрос: «А как бы ты помог герою в следующий раз?»";
    }

    public String parentSummaryPrompt(String dayStory){
        return "Для родительского экрана кратко, нейтрально и без диагнозов выдели из рассказа ребёнка: 1) что его порадовало; 2) что оказалось трудным; 3) какой навык можно потренировать через игру; 4) одну короткую идею игры на завтра. Рассказ: "+dayStory;
    }
}
